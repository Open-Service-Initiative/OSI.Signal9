using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using Microsoft.IdentityModel.Tokens;
using OSI.Signal9.Contracts.ApiApplications;
using OSI.Signal9.Server.Identity;
using Credential = OSI.Signal9.Server.Identity.ApiApplicationClient.Credential;

namespace OSI.Signal9.API.ApiApplications;

/// <summary>
/// Reads the credential an API application's method takes from a request (story 84): a self-signed certificate under
/// the one client certificate policy (<c>self_signed_tls_client_auth</c>), a public key or certificate a client
/// assertion can be verified with (<c>private_key_jwt</c>), or a client secret the server generates, of which only the
/// hash is kept.
/// </summary>
internal static class ApiApplicationCredentials
{
    /// <summary>How long a client secret lasts unless the request says otherwise.</summary>
    public static readonly TimeSpan DefaultSecretLifetime = TimeSpan.FromDays(180);

    /// <summary>The longest a client secret may last.</summary>
    public static readonly TimeSpan MaxSecretLifetime = TimeSpan.FromDays(365);

    /// <summary>Why the request holds no acceptable credential: the request field at fault (empty for the whole body).</summary>
    public sealed record Problem(string Field, string Message);

    /// <summary>
    /// The credential for an application authenticating with <paramref name="method"/>, and the generated secret when it
    /// is one, which is shown only once; or why there's none.
    /// </summary>
    public static async Task<(Credential? Credential, string? Secret, Problem? Problem)> CreateAsync(string method,
        CreateApiApplicationCredentialRequest request, DateTimeOffset now,
        Func<string, CancellationToken, ValueTask<string>> hashSecret, CancellationToken cancellationToken)
    {
        var id = Guid.CreateVersion7(now);
        switch (method)
        {
            case TokenEndpointAuthMethods.SelfSignedTlsClientAuth when request.CertificatePem is { } pem && request.PublicKeyPem is null:
                // The same certificate policy as an agent's (RFC 8705 §2.2).
                using (var certificate = SelfSignedClientCertificate.Read(pem, now, out var problem))
                {
                    return certificate is null
                        ? (null, null, new Problem(nameof(request.CertificatePem), problem!))
                        : (new Credential(id, ApiApplicationCredentialTypes.Certificate, now, certificate.NotAfter.ToUniversalTime(),
                            ApiApplicationClient.Thumbprint(certificate.RawData), certificate.Subject,
                            Certificate: Convert.ToBase64String(certificate.RawData)), null, null);
                }
            case TokenEndpointAuthMethods.PrivateKeyJwt when (request.CertificatePem is null) != (request.PublicKeyPem is null):
                return PublicKey(request, out var keyProblem) is { } spki
                    ? (new Credential(id, ApiApplicationCredentialTypes.PublicKey, now, null, ApiApplicationClient.Thumbprint(spki),
                        null, PublicKey: Convert.ToBase64String(spki)), null, null)
                    : (null, null, keyProblem);
            case TokenEndpointAuthMethods.ClientSecret when request.CertificatePem is null && request.PublicKeyPem is null:
                var expiresAt = request.ExpiresAt ?? now + DefaultSecretLifetime;
                if (expiresAt <= now || expiresAt > now + MaxSecretLifetime)
                    return (null, null, new Problem(nameof(request.ExpiresAt), "A secret must expire in the future, within a year."));
                // 256 bits from the CSPRNG; only its hash is kept.
                var secret = Base64UrlEncoder.Encode(RandomNumberGenerator.GetBytes(32));
                return (new Credential(id, ApiApplicationCredentialTypes.Secret, now, expiresAt, null, null,
                    SecretHash: await hashSecret(secret, cancellationToken)), secret, null);
            case TokenEndpointAuthMethods.TlsClientAuth:
                return (null, null, new Problem(string.Empty,
                    "A tls_client_auth application's credential is its certificate subject: change tlsClientAuthSubject."));
            default:
                return (null, null, new Problem(string.Empty, method switch
                {
                    TokenEndpointAuthMethods.SelfSignedTlsClientAuth => "Send certificatePem, the self-signed certificate.",
                    TokenEndpointAuthMethods.PrivateKeyJwt => "Send either publicKeyPem or certificatePem.",
                    _ => "A secret is generated by the server: send at most expiresAt.",
                }));
        }
    }

    /// <summary>The key, as SubjectPublicKeyInfo, if it's one a client assertion can be verified with.</summary>
    private static byte[]? PublicKey(CreateApiApplicationCredentialRequest request, out Problem? problem)
    {
        problem = null;
        byte[] spki;
        if (request.CertificatePem is { } pem)
        {
            try
            {
                using var certificate = X509Certificate2.CreateFromPem(pem);
                spki = certificate.PublicKey.ExportSubjectPublicKeyInfo();
            }
            catch (CryptographicException)
            {
                problem = new Problem(nameof(request.CertificatePem), "Not a PEM certificate.");
                return null;
            }
        }
        else
        {
            if (!PemEncoding.TryFind(request.PublicKeyPem, out var fields)
                || !request.PublicKeyPem.AsSpan()[fields.Label].SequenceEqual("PUBLIC KEY"))
            {
                problem = new Problem(nameof(request.PublicKeyPem), "Not a PEM public key (BEGIN PUBLIC KEY).");
                return null;
            }
            spki = Convert.FromBase64String(request.PublicKeyPem![fields.Base64Data]);
        }

        try
        {
            ApiApplicationClient.PublicKeyJwk(Guid.Empty, spki);
            return spki;
        }
        catch (CryptographicException exception)
        {
            problem = new Problem(request.CertificatePem is null ? nameof(request.PublicKeyPem) : nameof(request.CertificatePem),
                $"Unsupported key: {exception.Message} Use RSA of 2048 bits or more, or EC on P-256, P-384 or P-521.");
            return null;
        }
    }
}

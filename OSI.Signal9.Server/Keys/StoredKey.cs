namespace OSI.Signal9.Server.Keys;

/// <summary>What an authorization server key is for.</summary>
public enum StoredKeyUse
{
    /// <summary>Signs tokens with RS256.</summary>
    Signing,

    /// <summary>Encrypts tokens (RSA-OAEP key wrapping).</summary>
    Encryption,

    /// <summary>
    /// The <c>web</c> host's TLS client certificate, which it authenticates to <c>api</c> with
    /// (<c>self_signed_tls_client_auth</c>), so its tokens are bound to it (ADR-0003, ADR-0004).
    /// </summary>
    WebClient,
}

/// <summary>The keys a host manages: generates when due, loads and removes once retired.</summary>
public sealed class StoredKeysOptions
{
    /// <summary>The authorization server's own keys, which <c>auth</c> and <c>api</c> manage.</summary>
    public StoredKeyUse[] Uses { get; set; } = [StoredKeyUse.Signing, StoredKeyUse.Encryption];
}

/// <summary>
/// One of the authorization server's keys, generated by Signal9 (ADR-0008). The public half is a self-signed X.509
/// certificate whose NotBefore is <see cref="ActivatesAt"/>; the private key is sealed under the key-encryption key.
/// </summary>
public sealed class StoredKey
{
    public Guid Id { get; set; }
    public StoredKeyUse Use { get; set; }

    /// <summary>When the key starts being used: the certificate's NotBefore.</summary>
    public DateTime ActivatesAt { get; set; }

    /// <summary>The certificate's NotAfter.</summary>
    public DateTime ExpiresAt { get; set; }

    /// <summary>The DER-encoded certificate, without its private key.</summary>
    public required byte[] Certificate { get; set; }

    /// <summary>The key-encryption key that wrapped <see cref="WrappedKey"/>.</summary>
    public required string KekId { get; set; }

    /// <summary>The data-encryption key that encrypted <see cref="EncryptedPrivateKey"/>, wrapped by the key-encryption key.</summary>
    public required byte[] WrappedKey { get; set; }

    /// <summary>The PKCS#8 private key, encrypted with AES-256-GCM (nonce, ciphertext, tag).</summary>
    public required byte[] EncryptedPrivateKey { get; set; }
}
